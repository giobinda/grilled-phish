#!/usr/bin/env node
/*
 * Creates the key pair that signs the well-known-sites list.
 *
 *   node tools/keygen.js [--out ~/.config/grilled-phish/list-signing-key.pem]
 *
 * - The PRIVATE key is written outside the repository (mode 600). Keep a backup
 *   in a password manager; it goes to GitHub only as an environment secret
 *   (tools/setup-signing.sh). Never commit it.
 * - The PUBLIC key is added to lib/list-public-key.js, which ships inside the
 *   extension. Old public keys are kept so lists signed before a key change
 *   still verify; remove them once no installed version needs them.
 */
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const args = process.argv.slice(2);
const outArg = args.includes('--out') ? args[args.indexOf('--out') + 1] : null;
const OUT = outArg || path.join(os.homedir(), '.config', 'grilled-phish', 'list-signing-key.pem');
const PUB_FILE = path.join(__dirname, '..', 'lib', 'list-public-key.js');

if (fs.existsSync(OUT)) {
  console.error(`Refusing to overwrite existing key: ${OUT}`);
  process.exit(1);
}

const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
fs.mkdirSync(path.dirname(OUT), { recursive: true, mode: 0o700 });
fs.writeFileSync(OUT, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });

const spki = publicKey.export({ type: 'spki', format: 'der' }).toString('base64');
let keys = [];
if (fs.existsSync(PUB_FILE)) keys = require(PUB_FILE);
keys = [spki, ...keys.filter((k) => k !== spki)];

fs.writeFileSync(PUB_FILE, `/*
 * Public keys that may sign the well-known-sites list (base64 SPKI, ECDSA P-256).
 * Generated by tools/keygen.js. Newest first; older keys kept for rotation.
 */
(function (root) {
  const keys = ${JSON.stringify(keys, null, 2).replace(/\n/g, '\n  ')};
  if (typeof module !== 'undefined' && module.exports) module.exports = keys;
  root.GRILLED_PHISH_LIST_KEYS = keys;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`);

console.log(`Private key: ${OUT} (keep it secret, back it up)`);
console.log(`Public key added to ${path.relative(process.cwd(), PUB_FILE)}`);
